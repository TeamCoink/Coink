<section id="invest-meaning">
    <h2>2- ¿Qué significa invertir?</h2> <br>

    <p>Invertir consiste en destinar una parte de tu dinero a un activo o proyecto con el objetivo de obtener ganancias o hacer crecer ese dinero con el paso del tiempo. A diferencia del ahorro, donde el dinero permanece guardado, al invertir se pone a trabajar para generar un posible rendimiento.</p> <br>
            
</section>

